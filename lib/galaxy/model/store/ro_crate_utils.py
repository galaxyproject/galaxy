    def _add_parameters(self, crate: ROCrate):
        workflow_entity = getattr(self, "workflow_definitions", {}).get(
            getattr(self.invocation, "workflow_id", None), crate.mainEntity
        )
        for step in self.invocation.steps:
            if step.workflow_step.type == "parameter_input":
                property_value = self._add_step_parameter(step, crate)
                self.create_action.append_to("object", property_value)
        for output in self.invocation.output_values:
            name = output.workflow_output.label or output.workflow_output.output_name
            identifier = f"#workflow-{self.invocation.id}-scalar-output-{output.workflow_output.id}"
            parameter_type = {
                bool: "Boolean",
                int: "Integer",
                float: "Float",
                str: "Text",
                list: "Collection",
                dict: "Collection",
            }.get(type(output.value), "Text")
            parameter = crate.add(
                ContextEntity(
                    crate,
                    f"#workflow-definition-{getattr(self.invocation, 'workflow_id', self.invocation.id)}-scalar-output-{output.workflow_output.id}-parameter",
                    properties={"@type": "FormalParameter", "name": name, "additionalType": parameter_type},
                )
            )
            value = self._parameter_value(crate, identifier, name, output.value, parameter)
            workflow_entity.append_to("output", parameter)
            self.create_action.append_to("result", value)

    def _parameter_value(self, crate, identifier, name, value, parameter=None):
        properties = {"@type": "PropertyValue", "name": name or "Unnamed parameter"}
        if parameter is not None:
            properties["exampleOfWork"] = parameter
        if not self.model_store._safe_metadata_value(value):
            properties["description"] = "Value withheld by export privacy policy."
        elif value is None:
            properties["description"] = "No value was recorded."
        elif isinstance(value, str):
            properties["description"] = "Text value withheld because workflow parameters can contain credentials."
        elif isinstance(value, (list, dict)):
            properties["@type"] = "Collection"
            properties["additionalType"] = (
                "https://galaxyproject.org/parameter/record"
                if isinstance(value, dict)
                else "https://galaxyproject.org/parameter/list"
            )
            members, items = [], []
            for index, (label, item) in enumerate(value.items() if isinstance(value, dict) else enumerate(value)):
                member = self._parameter_value(crate, f"{identifier}-value-{index}", str(label), item)
                members.append(member)
                items.append(
                    crate.add(
                        ContextEntity(
                            crate,
                            f"{identifier}-item-{index}",
                            properties={"@type": "ListItem", "name": str(label), "position": index + 1, "item": member},
                        )
                    )
                )
            properties.update(hasPart=members, itemListElement=items, numberOfItems=len(members))
        else:
            properties["value"] = value
        return crate.add(ContextEntity(crate, identifier, properties=properties))

    def _add_step_parameter(self, step: WorkflowInvocationStep, crate: ROCrate) -> ContextEntity:
        param_id = step.workflow_step.label
        assert step.workflow_step.tool_inputs
        param_type = step.workflow_step.tool_inputs["parameter_type"]
        formal_param = crate.add(
            ContextEntity(
                crate,
                f"#workflow-definition-{self.invocation.workflow_id}-parameter-{step.workflow_step.id}",
                properties={
                    "@type": "FormalParameter",
                    "additionalType": self._get_parameter_additional_type(param_type),
                    "description": self._get_association_description(step.workflow_step),
                    "name": f"{param_id}",
                    "valueRequired": not step.workflow_step.input_optional,
                },
            )
        )
        workflow_entity = self.workflow_definitions.get(self.invocation.workflow_id, crate.mainEntity)
        workflow_entity.append_to("input", formal_param)
        tool_inputs = step.workflow_step.tool_inputs
        for name in ("default", "min", "max", "options"):
            value = tool_inputs.get(name)
            if is_publishable_metadata_field(param_id, value):
                self.model_store._add_metadata_property(crate, formal_param, f"Galaxy parameter {name}", value)

        # Handle case where output_value is None (e.g., optional parameter not provided)
        output_value = None
        if step.output_value:
            output_value = step.output_value.value
        else:
            for parameter in self.invocation.input_step_parameters:
                if parameter.workflow_step_id == step.workflow_step.id:
                    output_value = parameter.parameter_value
                    break
        return self._parameter_value(
            crate,
            f"#workflow-{self.invocation.id}-parameter-value-{step.workflow_step.id}",
            param_id,
            output_value,
            formal_param,
        )

    def _add_step_tool_fp(self, step: WorkflowInvocationStep, tool_input: str, crate: ROCrate):
        param_id = tool_input
        param_type = "text"
        return ContextEntity(
            crate,
            f"{param_id}-param",
            properties={
                "@type": "FormalParameter",
                "additionalType": self._get_parameter_additional_type(param_type),
                "description": self._get_association_description(step.workflow_step),
                "name": f"{step.workflow_step.label}",
                "valueRequired": not step.workflow_step.input_optional,
            },
        )

    def _add_dataset_formal_parameter(self, hda: HistoryDatasetAssociation, crate: ROCrate, identifier=None, name=None):
        assert hda.dataset is not None
        filename, _ = self.model_store.dataset_id_to_path.get(hda.dataset.id, (None, None))
        return crate.add(
            ContextEntity(
                crate,
                identifier or str(hda.dataset.uuid),
                properties={
                    "@type": "FormalParameter",
                    "additionalType": "File" if filename else "Dataset",
                    "description": self._get_association_description(hda),
                    "name": name or hda.name,
                },
            )
        )

    def _add_collection_formal_parameter(
        self, hdca: HistoryDatasetCollectionAssociation, crate: ROCrate, identifier=None, name=None
    ) -> ContextEntity:
        return crate.add(
            ContextEntity(
                crate,
                identifier or f"{hdca.type_id}-param",
                properties={
                    "@type": "FormalParameter",
                    "additionalType": "Collection",
                    "description": self._get_association_description(hdca),
                    "name": name or hdca.name,
                },
            )
        )

    def _get_association_description(self, association: Any) -> str:
        if hasattr(association, "annotations"):
            return association.annotations[0].annotation if association.annotations else ""
        elif hasattr(association, "info"):
            return association.info
        return ""
